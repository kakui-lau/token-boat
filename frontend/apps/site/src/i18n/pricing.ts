export function createPricingI18n(locale: "en" | "zh"): i18n {
  const instance = createInstance();
  void instance.use(initReactI18next).init({
    fallbackLng: "zh",
    initAsync: false,
    interpolation: { escapeValue: false },
    lng: locale,
    resources,
  });
  return instance;
}
